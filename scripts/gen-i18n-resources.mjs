// Regenerates src/i18n/index.ts (imports + resources for every locale) and
// normalizes the `language` native-name map across every locale's common.json.
// Run from repo root: node scripts/gen-i18n-resources.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const localesDir = join(root, 'src/i18n/locales');

// Ordered: en, uk first, then the order locales were added.
const LOCALES = [
  'en', 'uk', 'hr', 'tr', 'ro', 'bg', 'pl', 'it', 'es', 'fr', 'de', 'fa',
  'pt', 'zh', 'id', 'el', 'hu', 'ko', 'mk', 'sk', 'sq', 'sr', 'zh-TW', 'be',
];

// Native (endonym) names — constant across every catalog.
const NAMES = {
  en: 'English', uk: 'Українська', hr: 'Hrvatski', tr: 'Türkçe', ro: 'Română',
  bg: 'Български', pl: 'Polski', it: 'Italiano', es: 'Español', fr: 'Français',
  de: 'Deutsch', fa: 'فارسی', pt: 'Português', zh: '中文', id: 'Bahasa Indonesia',
  el: 'Ελληνικά', hu: 'Magyar', ko: '한국어', mk: 'Македонски', sk: 'Slovenčina',
  sq: 'Shqip', sr: 'Српски', 'zh-TW': '繁體中文', be: 'Беларуская',
};

const NS = ['common', 'industry', 'holdings', 'tooltips'];

// 1) Normalize the language map in every common.json (keep each file's own label).
for (const loc of LOCALES) {
  const file = join(localesDir, loc, 'common.json');
  const json = JSON.parse(readFileSync(file, 'utf8'));
  const label = json.language?.label ?? NAMES[loc];
  json.language = { label, ...NAMES };
  writeFileSync(file, JSON.stringify(json, null, 2) + '\n');
}

// 2) Generate index.ts.
const ident = (loc) => loc.replace(/[^a-zA-Z0-9]/g, '');           // zh-TW -> zhTW
const key = (loc) => (/[^a-zA-Z0-9]/.test(loc) ? `'${loc}'` : loc); // quoted if hyphen

const imports = LOCALES.flatMap((loc) =>
  NS.map((ns) => {
    const cap = ns[0].toUpperCase() + ns.slice(1);
    return `import ${ident(loc)}${cap} from './locales/${loc}/${ns}.json';`;
  }),
).join('\n');

const resourceEntries = LOCALES.map((loc) => {
  const cap = (ns) => ns[0].toUpperCase() + ns.slice(1);
  const lines = NS.map((ns) => `    ${ns}: ${ident(loc)}${cap(ns)},`).join('\n');
  return `  ${key(loc)}: {\n${lines}\n  },`;
}).join('\n');

const out = `import i18n from 'i18next';
import { initReactI18next } from 'react-i18next';
import { DEFAULT_LOCALE, loadLocale } from './config';
${imports}

// Resources for every supported locale. This file is GENERATED by
// scripts/gen-i18n-resources.mjs — re-run it after adding a locale folder
// rather than editing the import/resource lists by hand.
export const resources = {
${resourceEntries}
} as const;

// Synchronous init: resources are bundled JSON, so translated text is present on
// first render (no Suspense, no key flash, tests render immediately). Uses the
// global instance via initReactI18next — components need no <I18nextProvider>.
i18n.use(initReactI18next).init({
  resources,
  lng: loadLocale(),
  fallbackLng: DEFAULT_LOCALE,
  ns: ['common', 'industry', 'holdings', 'tooltips'],
  defaultNS: 'common',
  interpolation: { escapeValue: false },
  react: { useSuspense: false },
});

export default i18n;
`;

writeFileSync(join(root, 'src/i18n/index.ts'), out);

// 3) Generate src/components/flagUrls.ts — import ONLY the flag SVGs actually
// used (one country code per locale, read from config's LOCALE_FLAG), bundled as
// Vite assets. Avoids shipping the full flag-icons world-sprite CSS (~260 flags).
const cfg = readFileSync(join(root, 'src/i18n/config.ts'), 'utf8');
const flagBlock = cfg.match(/LOCALE_FLAG[^{]*\{([\s\S]*?)\}/)[1];
const codes = [...new Set([...flagBlock.matchAll(/:\s*'([a-z]{2})'/g)].map((m) => m[1]))].sort();

const flagImports = codes
  .map((c) => `import fi_${c} from 'flag-icons/flags/4x3/${c}.svg';`)
  .join('\n');
const flagMap = codes.map((c) => `  ${c}: fi_${c},`).join('\n');
const flagOut = `// GENERATED by scripts/gen-i18n-resources.mjs — do not edit by hand.
// Only the ${codes.length} flags actually used are imported (as Vite asset URLs),
// instead of shipping the full flag-icons world-sprite CSS.
${flagImports}

export const FLAG_URL: Record<string, string> = {
${flagMap}
};
`;
writeFileSync(join(root, 'src/components/flagUrls.ts'), flagOut);

console.log(
  `Wrote index.ts (${LOCALES.length} locales), normalized language maps, ` +
    `and flagUrls.ts (${codes.length} flags).`,
);
